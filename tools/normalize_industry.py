rows = list(csv.DictReader(open(P, encoding='utf-8-sig')))
changed, unmapped = 0, set()
for r in rows:
    old = r['industry']
    if not old:
        continue
    if old in M.get(r['sector'], {}):
        r['industry'] = M[r['sector']][old]
        changed += 1
    else:
        unmapped.add((r['sector'], old, r['id']))

if unmapped:
    print('未映射值（须补映射）:')
    for s, o, i in sorted(unmapped):
        print(f'  {i} [{s}] {o}')
    sys.exit(1)

